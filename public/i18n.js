/* English interface. Arabic stays the source of the page; when the viewer picks English this script
   translates the page as it is built and keeps translating whatever is added later (tables, toasts,
   server messages). Patient-written text (comments, notes, replies) is left as written. */
(function () {
  var lang = 'ar';
  try { lang = localStorage.getItem('pe_lang') === 'en' ? 'en' : 'ar'; } catch (e) { /* private mode */ }
  window.PE_LANG = lang;
  window.peSetLang = function (l) { try { localStorage.setItem('pe_lang', l); } catch (e) { /* ignore */ } location.reload(); };
  if (lang !== 'en') { window.tr = function (s) { return s; }; window.peAddNames = function () {}; return; }

  var root = document.documentElement;
  root.lang = 'en'; root.dir = 'ltr';
  var D = new Map(Object.entries(window.PE_DICT || {}));
  var AR = /[؀-ۿ]/;
  var RUN = /[؀-ۿ][؀-ۿ\s«»،؛؟!.\-:()\/]*[؀-ۿ»)!؟.]|[؀-ۿ]/g;
  var EDGE = /^([«("“]*)([\s\S]*?)([»)"”:.،؟!؛]*)$/;
  var PUNCT = { '،': ',', '؛': ';', '؟': '?', '«': '“', '»': '”', '٪': '%', '←': '→' };
  var fixPunct = function (s) { return s.replace(/[،؛؟«»٪←]/g, function (c) { return PUNCT[c]; }); };
  var maxWords = 1;
  D.forEach(function (_v, k) { var n = k.split(/\s+/).length; if (n > maxWords) maxWords = n; });

  function look(w) {
    if (D.has(w)) return D.get(w);
    var m = EDGE.exec(w);
    if (m && m[2] && D.has(m[2])) return fixPunct(m[1]) + D.get(m[2]) + fixPunct(m[3]);
    return null;
  }
  // One Arabic run: exact phrase, else longest known phrases word by word. A run that is mostly
  // unknown words (a name, a patient's sentence) is left as it is.
  function run(r) {
    var t = r.trim();
    if (!t) return r;
    var hit = look(t);
    if (hit !== null) return r.replace(t, hit);
    var w = t.split(/\s+/), out = [], known = 0, unknown = 0;
    for (var i = 0; i < w.length;) {
      var done = false;
      for (var j = Math.min(w.length, i + maxWords); j > i; j--) {
        var h = look(w.slice(i, j).join(' '));
        if (h !== null) { out.push(h); known += j - i; i = j; done = true; break; }
      }
      if (!done) { if (AR.test(w[i])) unknown++; out.push(w[i]); i++; }
    }
    if (!known || (unknown > 3 && unknown >= known)) return r;
    return r.replace(t, fixPunct(out.join(' ')));
  }
  function tr(s) {
    if (s == null) return s;
    s = String(s);
    if (!AR.test(s)) return s;
    var t = s.trim(), hit = look(t);
    if (hit !== null) return s.replace(t, hit);
    return fixPunct(s.replace(RUN, run).replace(/[،؛؟]/g, function (c) { return PUNCT[c]; }));
  }
  window.tr = tr;
  // Names that have an English form (doctors from the lookups) are added once known.
  window.peAddNames = function (pairs) {
    var n = 0;
    (pairs || []).forEach(function (p) { if (p && p[0] && p[1] && AR.test(p[0]) && !AR.test(p[1]) && D.get(p[0]) !== p[1]) { D.set(p[0], p[1]); n++; } });
    if (n && document.body) walk(document.body);
  };

  var SKIP = 'script,style,textarea,.quote,.txt,.reply,.wrap-t,.case-events .b,[data-ugc]';
  var ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
  function skipEl(el) { return !el || (el.closest && el.closest(SKIP)); }
  function doText(n) {
    if (!AR.test(n.data) || skipEl(n.parentElement)) return;
    var v = tr(n.data);
    if (v !== n.data) n.data = v;
  }
  function doAttrs(el) {
    for (var i = 0; i < ATTRS.length; i++) {
      var a = el.getAttribute(ATTRS[i]);
      if (a && AR.test(a)) el.setAttribute(ATTRS[i], tr(a));
    }
    if (el.tagName === 'INPUT' && /^(button|submit)$/i.test(el.type) && AR.test(el.value)) el.value = tr(el.value);
  }
  function walk(node) {
    if (node.nodeType === 3) { doText(node); return; }
    if (node.nodeType !== 1 || skipEl(node)) return;
    doAttrs(node);
    var it = document.createTreeWalker(node, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) { return n.nodeType === 1 && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT; }
    });
    var n;
    while ((n = it.nextNode())) { if (n.nodeType === 3) doText(n); else doAttrs(n); }
  }
  new MutationObserver(function (list) {
    for (var i = 0; i < list.length; i++) {
      var m = list[i];
      if (m.type === 'childList') for (var k = 0; k < m.addedNodes.length; k++) walk(m.addedNodes[k]);
      else if (m.type === 'characterData') doText(m.target);
      else if (m.type === 'attributes' && m.target.nodeType === 1 && !skipEl(m.target)) {
        var a = m.target.getAttribute(m.attributeName);
        if (a && AR.test(a)) m.target.setAttribute(m.attributeName, tr(a));
      }
    }
  }).observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  walk(root);
  var c = window.confirm, al = window.alert;
  window.confirm = function (m) { return c.call(window, tr(m)); };
  window.alert = function (m) { return al.call(window, tr(m)); };
})();
